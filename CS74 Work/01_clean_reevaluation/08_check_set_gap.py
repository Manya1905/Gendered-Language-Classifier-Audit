"""
E1 follow-up: why do all models score lower on the new evaluation set than on the clean test?

Observation (FINDINGS F18): BERT (clean) 0.817 on test_b vs 0.784 on the new set (unseen),
and the drop is mostly in MASCULINE F1 (0.758 -> 0.684). The list rule doesn't drop.
Both sets contain only unseen companies, so leakage can't explain it.

This script compares the two sets (no models are run; it reads saved predictions):
  Check 1  which class drops: per-class precision / recall / F1 for each model family
  Check 2  how the sets differ, focusing on masculine sentences:
             - label mix, list words per sentence, sentence length
             - share of masculine labels that came from Claude's "both" (F14)
             - model recall on "both"-masculine vs pure-masculine sentences
             - which masculine list words the masculine sentences contain

Usage:  python 08_check_set_gap.py      (local; needs results/predictions/ from 05)
Saves:  results/set_gap_check.md
"""
from pathlib import Path

import pandas as pd
from sklearn.metrics import precision_recall_fscore_support

HERE = Path(__file__).resolve().parent
DATA, RES = HERE / "data", HERE / "results"
KEYS = ["source", "job_id", "sentence_num"]
FAMILIES = {"BERT (clean)": "bert", "RoBERTa (clean)": "roberta"}
SEEDS = [42, 43, 44]


def load_sets():
    test_b = pd.read_csv(DATA / "test_b.csv", dtype={"job_id": str})
    new = pd.read_csv(DATA / "new_eval.csv", dtype={"job_id": str})
    new = new[~new.seen_in_annotated]                    # the headline (unseen) version
    return {"test_b": test_b, "new_unseen": new}


def words(cell):
    return [w for w in str(cell).split(", ") if w] if isinstance(cell, str) else []


def preds_for(tag, set_name, df):
    """Saved predictions for one model, aligned to df's rows."""
    file = "new_eval" if set_name == "new_unseen" else set_name
    p = pd.read_csv(RES / "predictions" / f"{tag}_{file}.csv", dtype={"job_id": str})
    m = df[KEYS].merge(p[KEYS + ["pred_id"]], on=KEYS, how="left", validate="one_to_one")
    assert m.pred_id.notna().all()
    return m.pred_id.values


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return out


def main():
    sets = load_sets()
    for d in sets.values():
        d["from_both"] = d["suggested_label"].eq("both")      # masculine label that was "both"
        d["n_list_words"] = d.masculine_words.map(lambda c: len(words(c))) + \
            d.feminine_words.map(lambda c: len(words(c)))
        d["n_words"] = d.sentence_text.str.split().str.len()

    lines = ["# Why do models score lower on the new set than on the clean test?", "",
             "Compares test_b (clean test) with the new evaluation set (unseen version).",
             "Model numbers are the mean over 3 seeds. Generated by `08_check_set_gap.py`.", ""]

    # ── Check 1: which class drops ──
    lines += ["## Check 1: which class drops", ""]
    rows = []
    for fam, tag in FAMILIES.items():
        for set_name, d in sets.items():
            per_seed = [precision_recall_fscore_support(d.label_id, preds_for(f"{tag}_seed{s}", set_name, d),
                                                        labels=[0, 1, 2], zero_division=0)[:3] for s in SEEDS]
            for i, cls in enumerate(["neutral", "masculine", "feminine"]):
                p, r, f = (sum(x[k][i] for x in per_seed) / 3 for k in range(3))
                rows.append({"Model": fam, "Set": set_name, "Class": cls,
                             "Precision": f"{p:.3f}", "Recall": f"{r:.3f}", "F1": f"{f:.3f}"})
    t = pd.DataFrame(rows).sort_values(["Model", "Class", "Set"], key=lambda c: c.map(
        {"neutral": 0, "masculine": 1, "feminine": 2}) if c.name == "Class" else c)
    lines += md_table(t) + [""]

    # ── Check 2a: how the sets differ ──
    lines += ["## Check 2a: how the two sets differ", ""]
    rows = []
    for set_name, d in sets.items():
        masc, fl = d[d.label == "masculine"], d[d.flagged]
        rows.append({
            "Set": set_name, "Sentences": len(d),
            "Masculine %": f"{100 * (d.label == 'masculine').mean():.1f}",
            "Feminine %": f"{100 * (d.label == 'feminine').mean():.1f}",
            "Flagged %": f"{100 * d.flagged.mean():.1f}",
            "List words per flagged sentence": f"{fl.n_list_words.mean():.2f}",
            "Words per sentence": f"{d.n_words.mean():.1f}",
            "Masculine labels that were 'both' %": f"{100 * masc.from_both.mean():.1f}",
            "Masculine sentences with no masculine list word %":
                f"{100 * masc.masculine_words.map(lambda c: len(words(c)) == 0).mean():.1f}",
        })
    lines += md_table(pd.DataFrame(rows).T.reset_index().rename(columns={"index": "Measure"})
                      .pipe(lambda x: x.set_axis(["Measure"] + [r["Set"] for r in rows], axis=1)).iloc[1:]) + [""]

    # ── Check 2b: model recall on the two kinds of masculine sentence ──
    lines += ["## Check 2b: masculine recall, split by where the label came from", "",
              "'both' = Claude said both masculine and feminine (counted as masculine, F14).", ""]
    rows = []
    for fam, tag in FAMILIES.items():
        for set_name, d in sets.items():
            for kind, mask in [("pure masculine", (d.label == "masculine") & ~d.from_both),
                               ("'both' -> masculine", (d.label == "masculine") & d.from_both)]:
                rec = sum((preds_for(f"{tag}_seed{s}", set_name, d)[mask.values] == 1).mean() for s in SEEDS) / 3
                rows.append({"Model": fam, "Set": set_name, "Kind": kind, "n": int(mask.sum()),
                             "Recall (predicted masculine)": f"{rec:.3f}"})
    lines += md_table(pd.DataFrame(rows)) + [""]

    # ── Check 2c: which masculine list words the masculine sentences contain ──
    lines += ["## Check 2c: masculine list words in masculine-labeled sentences", "",
              "Share of masculine-labeled sentences containing each word (top 12 in either set).", ""]
    share = {}
    for set_name, d in sets.items():
        masc = d[d.label == "masculine"]
        share[set_name] = masc.masculine_words.map(lambda c: set(words(c))).explode().value_counts() / len(masc)
    top = (share["test_b"].add(share["new_unseen"], fill_value=0)).sort_values(ascending=False).index[:12]
    t = pd.DataFrame({"Word": top,
                      "test_b %": [f"{100 * share['test_b'].get(w, 0):.1f}" for w in top],
                      "new_unseen %": [f"{100 * share['new_unseen'].get(w, 0):.1f}" for w in top]})
    lines += md_table(t) + [""]

    # ── Check 2d: where the false "masculine" predictions come from ──
    # Check 1 shows the masculine drop is mostly precision: more sentences predicted masculine
    # that Claude labeled neutral/feminine. Which list words are in those sentences?
    lines += ["## Check 2d: false 'masculine' predictions (BERT, mean over 3 seeds)", "",
              "False positive = BERT says masculine, Claude's label is neutral or feminine.", ""]
    rows, fp_words = [], {}
    for set_name, d in sets.items():
        fps = [(preds_for(f"bert_seed{s}", set_name, d) == 1) & (d.label_id.values != 1) for s in SEEDS]
        n_fp = sum(f.sum() for f in fps) / 3
        rows.append({"Set": set_name, "False positives": f"{n_fp:.0f}",
                     "per 1,000 sentences": f"{1000 * n_fp / len(d):.1f}",
                     "of which labeled neutral %": f"{100 * sum((d.label_id.values[f] == 0).sum() for f in fps) / 3 / n_fp:.0f}"})
        cnt = pd.concat([d.masculine_words[f].map(lambda c: set(words(c))).explode() for f in fps]).value_counts() / 3
        fp_words[set_name] = 1000 * cnt / len(d)
    lines += md_table(pd.DataFrame(rows)) + ["",
              "False positives containing each masculine list word, per 1,000 sentences:", ""]
    top = fp_words["test_b"].add(fp_words["new_unseen"], fill_value=0).sort_values(ascending=False).index[:10]
    lines += md_table(pd.DataFrame({"Word": top,
                                    "test_b": [f"{fp_words['test_b'].get(w, 0):.1f}" for w in top],
                                    "new_unseen": [f"{fp_words['new_unseen'].get(w, 0):.1f}" for w in top]})) + [""]

    (RES / "set_gap_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
