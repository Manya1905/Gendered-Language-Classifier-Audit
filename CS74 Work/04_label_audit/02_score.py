"""
E4 step 2: score the blind human labels against Claude's labels and the models.

Inputs:
  labeling/blind_labeling_sheet.xlsx   my labels (Label, Notes)
  labeling/sheet_key.csv               which row is which sentence / group
  01_clean_reevaluation/data/new_eval.csv              Claude's labels
  01_clean_reevaluation/results/predictions/*_new_eval.csv   saved model + rule predictions

Labels use the training convention: 'both' -> masculine.

Parts:
  A  Me vs. Claude on the 99 core sentences (33 per Claude label): agreement, kappa, confusion.
     Also re-weighted to the natural mix of Claude labels among flagged sentences, since the
     33/33/33 sample over-represents masculine/feminine.
  B  The 20 extra sentences (Claude neutral, BERT masculine): what did I say?
  C  Models and keyword rules scored against my labels vs. against Claude's (same sentences).
  D  Where we disagree: which list words, by group, plus my notes.

Usage:  python 02_score.py
Saves:  results/e4_summary.md, results/e4_per_sentence.csv
"""
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import cohen_kappa_score, f1_score

HERE = Path(__file__).resolve().parent
E1 = HERE.parent / "01_clean_reevaluation"
RES = HERE / "results"
KEYS = ["source", "job_id", "sentence_num"]
CLASSES = ["neutral", "masculine", "feminine"]
TO_ID = {c: i for i, c in enumerate(CLASSES)}
LABELERS = {"Original (CS72)": ["original"],
            "BERT (clean)": [f"bert_seed{s}" for s in (42, 43, 44)],
            "RoBERTa (clean)": [f"roberta_seed{s}" for s in (42, 43, 44)],
            "List rule": ["list_rule"],
            "Learned rule (clean train)": ["learned_clean"],
            "Learned rule (CS72 train)": ["learned_cs72"]}


def load():
    sheet = pd.read_excel(HERE / "labeling" / "blind_labeling_sheet.xlsx", sheet_name="Sentences")
    sheet = sheet[sheet.ID.notna()].astype({"ID": int})
    key = pd.read_csv(HERE / "labeling" / "sheet_key.csv", dtype={"job_id": str})
    d = key.merge(sheet[["ID", "Label", "Notes"]], left_on="sheet_id", right_on="ID", validate="one_to_one")
    assert len(d) == 119 and d.Label.notna().all(), "every row needs a label"
    d["my_raw"] = d.Label.str.strip().str.lower()
    assert d.my_raw.isin(CLASSES + ["both"]).all()
    d["mine"] = d.my_raw.replace({"both": "masculine"})

    ne = pd.read_csv(E1 / "data" / "new_eval.csv", dtype={"job_id": str})
    d = d.merge(ne[KEYS + ["industry", "sentence_text", "masculine_words", "feminine_words",
                           "suggested_label", "reasoning", "label"]], on=KEYS, validate="one_to_one")
    d = d.rename(columns={"label": "claude", "suggested_label": "claude_raw"})

    for tags in LABELERS.values():
        for t in tags:
            p = pd.read_csv(E1 / "results" / "predictions" / f"{t}_new_eval.csv", dtype={"job_id": str})
            m = d[KEYS].merge(p[KEYS + ["pred"]], on=KEYS, how="left", validate="one_to_one")
            assert m.pred.notna().all()
            d[f"pred_{t}"] = m.pred.values
    # natural share of each Claude label among flagged, unseen new-set sentences
    flagged = ne[ne.flagged & ~ne.seen_in_annotated]
    natural = flagged.label.value_counts(normalize=True)
    return d, natural


def md(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    return out + ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]


def agreement(a, b, w=None):
    w = np.ones(len(a)) if w is None else np.asarray(w)
    return float((w * (np.asarray(a) == np.asarray(b))).sum() / w.sum())


def main():
    d, natural = load()
    core = d[d.group.str.startswith("claude_")].copy()
    extra = d[d.group == "bert_false_masculine"].copy()
    # weight so each Claude-label group counts by its natural share among flagged sentences
    core["w"] = core.claude.map(natural) / core.claude.map(core.claude.value_counts(normalize=True))

    L = ["# E4: does Claude's labeling match a human's?", "",
         "Blind labels (me) on 119 flagged, unseen new-set sentences. 'both' counted as masculine.",
         "Generated by `02_score.py`.", ""]

    # ── A: me vs. Claude ──
    L += ["## A. Me vs. Claude (99 core sentences, 33 per Claude label)", ""]
    k = cohen_kappa_score(core.claude, core.mine)
    L += [f"- Agreement: **{agreement(core.claude, core.mine):.1%}**, Cohen's kappa **{k:.2f}**",
          f"- Re-weighted to the natural mix of Claude labels among flagged sentences "
          f"({', '.join(f'{c} {natural[c]:.0%}' for c in CLASSES)}): agreement "
          f"**{agreement(core.claude, core.mine, core.w):.1%}**",
          f"- My label mix: {', '.join(f'{c} {n}' for c, n in core.mine.value_counts().items())} "
          f"(4-class: {', '.join(f'{c} {n}' for c, n in core.my_raw.value_counts().items())})", "",
          "Rows = Claude, columns = me:", ""]
    cm = pd.crosstab(core.claude, core.mine).reindex(index=CLASSES, columns=CLASSES, fill_value=0)
    L += md(cm.reset_index().rename(columns={"claude": "Claude \\ me"})) + [""]
    rows = []
    for c in CLASSES:
        g = core[core.claude == c]
        rows.append({"Claude said": c, "n": len(g), "I agreed": f"{(g.mine == c).mean():.0%}",
                     "I said neutral": f"{(g.mine == 'neutral').mean():.0%}"})
    L += md(pd.DataFrame(rows)) + [""]
    # the reverse direction: when I call something gendered, does Claude?
    mine_g = core[core.mine != "neutral"]
    L += [f"- When I said gendered ({len(mine_g)} sentences), Claude gave the same label "
          f"{(mine_g.claude == mine_g.mine).mean():.0%} of the time and said neutral "
          f"{(mine_g.claude == 'neutral').mean():.0%}.", ""]

    # ── B: the 20 extra ──
    L += ["## B. The 20 false-alarm sentences (Claude neutral, BERT masculine in >= 2 of 3 seeds)", ""]
    vc = extra.mine.value_counts()
    L += [f"- My labels: {', '.join(f'{c} {vc.get(c, 0)}' for c in CLASSES)}",
          f"- So for {vc.get('neutral', 0)} of 20 I agree with Claude (BERT over-called); "
          f"for {vc.get('masculine', 0)} I agree with BERT (Claude under-called).", ""]

    # ── C: models vs. me and vs. Claude ──
    L += ["## C. Models scored against my labels vs. against Claude's", "",
          "Same 99 core sentences. Macro-F1 over the 3 classes; mean over seeds where there are 3.",
          "Note: my labels have few masculine/feminine sentences, so macro-F1 against me is noisy.", ""]
    rows = []
    for name, tags in LABELERS.items():
        r = {"Labeler": name}
        for ref, col in [("Claude", "claude"), ("me", "mine")]:
            acc = np.mean([agreement(core[col], core[f"pred_{t}"]) for t in tags])
            f1 = np.mean([f1_score(core[col], core[f"pred_{t}"], labels=CLASSES, average="macro",
                                   zero_division=0) for t in tags])
            r[f"Acc vs {ref}"], r[f"Macro-F1 vs {ref}"] = f"{acc:.3f}", f"{f1:.3f}"
        r["% predicted gendered"] = f"{np.mean([(core[f'pred_{t}'] != 'neutral').mean() for t in tags]):.0%}"
        rows.append(r)
    rows.append({"Labeler": "Claude", "Acc vs Claude": "1.000", "Macro-F1 vs Claude": "1.000",
                 "Acc vs me": f"{agreement(core.mine, core.claude):.3f}",
                 "Macro-F1 vs me": f"{f1_score(core.mine, core.claude, labels=CLASSES, average='macro', zero_division=0):.3f}",
                 "% predicted gendered": f"{(core.claude != 'neutral').mean():.0%}"})
    rows.append({"Labeler": "Me", "Acc vs Claude": f"{agreement(core.claude, core.mine):.3f}",
                 "Macro-F1 vs Claude": f"{f1_score(core.claude, core.mine, labels=CLASSES, average='macro', zero_division=0):.3f}",
                 "Acc vs me": "1.000", "Macro-F1 vs me": "1.000",
                 "% predicted gendered": f"{(core.mine != 'neutral').mean():.0%}"})
    L += md(pd.DataFrame(rows)[["Labeler", "Acc vs Claude", "Acc vs me", "Macro-F1 vs Claude",
                                "Macro-F1 vs me", "% predicted gendered"]]) + [""]
    allneu = (core.mine == "neutral").mean()
    L += [f"- Reference: always saying 'neutral' gets accuracy {allneu:.3f} against my labels "
          f"and {(core.claude == 'neutral').mean():.3f} against Claude's.", ""]

    # ── D: where we disagree ──
    L += ["## D. Where Claude and I disagree (all 119)", ""]
    dis = d[d.claude != d.mine]
    L += [f"- {len(dis)} of 119 disagree. Direction: "
          + ", ".join(f"Claude {a} / me {b}: {n}" for (a, b), n in
                      dis.groupby(["claude", "mine"]).size().sort_values(ascending=False).items()), ""]

    def wl(r):
        return [w for c in (r.masculine_words, r.feminine_words) if isinstance(c, str) for w in c.split(", ") if w]
    d["list_words"] = d.apply(wl, axis=1)
    ex = d.explode("list_words")
    word = ex.groupby("list_words").agg(n=("mine", "size"),
                                        claude_gendered=("claude", lambda s: (s != "neutral").sum()),
                                        me_gendered=("mine", lambda s: (s != "neutral").sum()))
    word = word[word.n >= 3].sort_values(["n", "claude_gendered"], ascending=False).head(15)
    L += ["List words appearing in 3+ sheet sentences: how often each of us called the sentence gendered.", ""]
    L += md(word.reset_index().rename(columns={"list_words": "Word", "n": "Sentences",
                                               "claude_gendered": "Claude gendered", "me_gendered": "Me gendered"})) + [""]

    by_ind = d.groupby("industry").apply(lambda g: pd.Series({
        "n": len(g), "Claude gendered %": f"{(g.claude != 'neutral').mean():.0%}",
        "Me gendered %": f"{(g.mine != 'neutral').mean():.0%}",
        "Agree %": f"{(g.claude == g.mine).mean():.0%}"}), include_groups=False)
    L += ["By industry (all 119; small n):", ""] + md(by_ind.reset_index()) + [""]

    noted = d[d.Notes.notna()]
    L += [f"### My notes ({len(noted)})", ""]
    for r in noted.itertuples():
        L += [f"- **#{r.sheet_id}** (me: {r.my_raw}, Claude: {r.claude_raw}) \"{r.sentence_text[:160]}"
              f"{'...' if len(r.sentence_text) > 160 else ''}\" — *{r.Notes}*"]
    L += [""]

    # ── E: my note — is every "analytical" sentence called masculine? (whole unseen new set) ──
    ne = pd.read_csv(E1 / "data" / "new_eval.csv", dtype={"job_id": str})
    ne = ne[~ne.seen_in_annotated]
    an = ne[ne.masculine_words.fillna("").str.split(", ").map(lambda l: "analytical" in l)]
    L += ["## E. Is every sentence with \"analytical\" called masculine? (all unseen new-set sentences)", "",
          f"{len(an)} sentences contain \"analytical\". Share labeled/predicted masculine:", ""]
    rows = [{"Labeler": "Claude", "Masculine": f"{(an.label == 'masculine').sum()}/{len(an)}"}]
    for name, tags in LABELERS.items():
        vals = []
        for t in tags:
            p = pd.read_csv(E1 / "results" / "predictions" / f"{t}_new_eval.csv", dtype={"job_id": str})
            vals.append((an[KEYS].merge(p[KEYS + ["pred"]], on=KEYS).pred == "masculine").sum())
        rows.append({"Labeler": name, "Masculine": f"{np.mean(vals):.0f}/{len(an)}"})
    sh = d[d.list_words.map(lambda l: "analytical" in l)]
    rows.append({"Labeler": f"Me (only the {len(sh)} on my sheet)", "Masculine": f"{(sh.mine == 'masculine').sum()}/{len(sh)}"})
    L += md(pd.DataFrame(rows)) + [""]

    RES.mkdir(exist_ok=True)
    keep = ["sheet_id", "group", "industry", "sentence_text", "masculine_words", "feminine_words",
            "my_raw", "mine", "Notes", "claude_raw", "claude", "reasoning"] + [c for c in d if c.startswith("pred_")]
    d.sort_values("sheet_id")[keep].to_csv(RES / "e4_per_sentence.csv", index=False)
    (RES / "e4_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
